export function renderPixelText(el) {
  const text = el.textContent.trim();
  const chars = [...text];
  let d = '';

  chars.forEach((ch, i) => {
    GLYPHS[ch]?.forEach((row, y) => {
      for (const run of row.matchAll(/#+/g)) {
        d += `M${i * CELL + run.index} ${y}h${run[0].length}v1h-${run[0].length}z`;
      }
    });
  });

  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${chars.length * CELL} ${CELL}`);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', 'pixel-text');
  svg.style.setProperty('--cols', chars.length);

  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', 'currentColor');
  svg.append(path);

  const label = document.createElement('span');
  label.className = 'visually-hidden';
  label.textContent = text;

  el.replaceChildren(label, svg);
}
